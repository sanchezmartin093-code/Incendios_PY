"""
raster.py module: Conversion of tabular GeoParquet alerts to standard GeoTIFF raster coverages (EPSG:32721).
Enables direct interoperability with desktop GIS (QGIS, ArcGIS) and cloud platforms (Google Earth Engine).
- Spatial resolution: 1 000 m x 1 000 m (1 km²).
- Projection: UTM Zone 21 South (EPSG:32721).
- Exported bands (both Float32, NoData = -9999.0):
  * Band 1: Calibrated fire probability P(Fire|X) ∈ [0.0, 1.0].
  * Band 2: Operational alert level:
    0 = NULO, 1 = BAJO, 2 = MODERADO, 3 = ALTO, 4 = EXTREMO.
"""

from pathlib import Path
import numpy as np
import polars as pl
import rasterio
from rasterio.transform import from_origin

from src.constantes import CRS_PROYECTADO

MAPA_NIVELES_INT = {
    "NULO": 0,
    "BAJO": 1,
    "MODERADO": 2,
    "ALTO": 3,
    "EXTREMO": 4
}

def exportar_alerta_a_geotiff(ruta_parquet_alerta: Path, ruta_salida_tif: Path) -> Path:
    """
    Converts a daily Parquet alert layer generated by the pipeline into a multi-band GeoTIFF.
    """
    if not ruta_parquet_alerta.exists():
        raise FileNotFoundError(f"Archivo Parquet de alerta no encontrado en {ruta_parquet_alerta}")

    df = pl.read_parquet(ruta_parquet_alerta)
    fecha = ruta_parquet_alerta.stem.replace("alerta_nacional_", "")

    res = 1000.0

    # The extent is derived from the alert layer to avoid misalignment
    # if the national grid changes.
    min_x = float(df["x_utm"].min())
    max_x = float(df["x_utm"].max())
    min_y = float(df["y_utm"].min())
    max_y = float(df["y_utm"].max())

    cols = int(round((max_x - min_x) / res)) + 1
    rows = int(round((max_y - min_y) / res)) + 1

    # Create 2D arrays initialized with NoData
    nodata_val = -9999.0

    matriz_prob = np.full((rows, cols), nodata_val, dtype=np.float32)
    matriz_nivel = np.full((rows, cols), nodata_val, dtype=np.float32)

    # Coordinates to row/column indices
    x_coords = df["x_utm"].to_numpy()
    y_coords = df["y_utm"].to_numpy()
    r_idx = np.round((max_y - y_coords) / res).astype(int)
    c_idx = np.round((x_coords - min_x) / res).astype(int)

    # Values
    probs = df["probabilidad_fuego"].to_numpy().astype(np.float32)
    niveles_str = df["nivel_alerta"].to_list()
    niveles_float = np.array([float(MAPA_NIVELES_INT.get(n, nodata_val)) for n in niveles_str], dtype=np.float32)

    # Assign to the raster array
    matriz_prob[r_idx, c_idx] = probs
    matriz_nivel[r_idx, c_idx] = niveles_float

    # Configure the geotransform (upper-left corner of the origin cell)
    transform = from_origin(min_x - res / 2.0, max_y + res / 2.0, res, res)

    ruta_salida_tif.parent.mkdir(parents=True, exist_ok=True)

    profile = {
        "driver": "GTiff",
        "height": rows,
        "width": cols,
        "count": 2,
        "dtype": rasterio.float32,
        "crs": CRS_PROYECTADO,
        "transform": transform,
        "compress": "deflate",
        "nodata": nodata_val,
        "tiled": True,
        "blockxsize": 256,
        "blockysize": 256
    }

    with rasterio.open(ruta_salida_tif, "w", **profile) as dst:
        dst.write(matriz_prob, 1)
        dst.write(matriz_nivel, 2)
        dst.set_band_description(1, "Probabilidad_Calibrada_Fuego")
        dst.set_band_description(2, "Nivel_Alerta_Operativo_0a4")
        dst.update_tags(
            FECHA_ALERTA=fecha,
            SISTEMA="SAT-Incendios PY",
            RESOLUCION_METROS="1000",
            LICENCIA="MIT Open Source",
            DESCRIPCION="Riesgo de incendios forestales estimado con LightGBM y calibracion monotonica de Platt"
        )

    return ruta_salida_tif
